package com.itesaurabh.deskflowclient

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context

/** Called on the main thread. Never logs or persists clipboard contents. */
class ClipboardSync(context: Context, private val send: (String) -> Unit) {
    private val manager = context.getSystemService(ClipboardManager::class.java)
    private var lastText: String? = null
    private val listener = ClipboardManager.OnPrimaryClipChangedListener { publish() }
    fun start() { manager.addPrimaryClipChangedListener(listener) }
    fun stop() { manager.removePrimaryClipChangedListener(listener) }
    fun publish() {
        if (ClientState.phase != ClientState.Phase.Connected) return
        try {
            val clip = manager.primaryClip ?: return // Only foreground reads are guaranteed when retaining another default IME.
            if (clip.description.extras?.getBoolean("android.content.extra.IS_SENSITIVE") == true) return
            val text = clip.getItemAt(0).text?.toString() ?: return
            if (text == lastText) return
            if (text.toByteArray(Charsets.UTF_8).size > ClipboardWire.LIMIT - 12) {
                Logs.warn("Clipboard too large; not synchronized")
                return
            }
            lastText = text
            send(text)
        } catch (_: SecurityException) { Logs.warn("Background clipboard read denied; use Deskflow copy shortcut or return to the app") }
    }
    fun publishSelection(text: String) {
        if (ClientState.phase != ClientState.Phase.Connected) return
        if (text.toByteArray(Charsets.UTF_8).size > ClipboardWire.LIMIT - 12) {
            Logs.warn("Selection too large; not synchronized")
            return
        }
        if (text == lastText) return
        lastText = text
        send(text)
    }
    fun resetSession() { lastText = null }
    fun receive(text: String) {
        lastText = text // Suppress the callback generated by our own write.
        try {
            val existing = manager.primaryClip?.getItemAt(0)?.text?.toString()
            if (existing == text) return
            manager.setPrimaryClip(ClipData.newPlainText("Deskflow", text))
            Logs.add("Clipboard received from Deskflow")
        } catch (_: SecurityException) { Logs.warn("Clipboard write denied") }
    }
}
